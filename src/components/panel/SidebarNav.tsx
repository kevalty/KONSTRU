export function SidebarNav() {
  const pathname = usePathname()
  return (
    <ul className="flex md:flex-col gap-0.5 md:gap-0.5 px-2 md:px-3 overflow-x-auto md:overflow-visible">
      {NAV_ITEMS.map(item => {
        const active = item.exact
          ? pathname === item.href
          : pathname === item.href || pathname.startsWith(item.href + '/')
        return (
          <li key={item.href} className="flex-shrink-0 md:flex-shrink">
            <Link
              href={item.href}
              className={`flex items-center gap-2.5 px-3 py-2.5 text-sm rounded-lg transition-colors min-h-[44px] whitespace-nowrap ${
                active
                  ? 'bg-emerald-500/10 text-emerald-400 font-medium'
                  : 'text-[#64748B] hover:bg-[#1E293B] hover:text-[#F8FAFC]'
              }`}
            >
              <span className="flex-shrink-0">{item.icon}</span>
              <span>{item.label}</span>
            </Link>
          </li>
        )
      })}
    </ul>
  )
}
